import json

import pytest

from dotfiles import backup, cli, restore


def test_ssh_config_parsing(tmp_path, monkeypatch):
    monkeypatch.setattr(restore, "home", lambda: tmp_path)
    ssh = tmp_path / ".ssh"
    ssh.mkdir()
    (ssh / "config").write_text(
        "# comment\n"
        "Host github.com\n"
        "    IdentityFile ~/.ssh/gh_key     # trailing comment\n"
        "Host srv\n"
        "    IdentityFile=\"~/.ssh/with space\"\n"
        "    identityfile %d/.ssh/third\n",
        encoding="utf-8")
    monkeypatch.setenv("HOME", str(tmp_path))
    keys, github = restore._ssh_config_keys()
    assert [k.name for k in keys] == ["id_ed25519", "gh_key", "with space", "third"]
    assert github.name == "gh_key"


@pytest.mark.parametrize("line, ok", [
    ("AGE-SECRET-KEY-1" + "Q" * 58, True),   # built at runtime: the full key format never appears in the source
    ("# public key: age1abc", False),
    ("age-secret-key-1lowercase", False),
])
def test_key_line_format(line, ok):
    assert bool(restore._KEY_RX.match(line)) is ok


def test_home_path_detection(tmp_path, monkeypatch):
    fake_home = tmp_path / "alice"
    monkeypatch.setattr(backup, "home", lambda: fake_home)
    f = tmp_path / "f"
    for text, hit in [(f"{fake_home}/x", True), (r"C:\Users\alice\x", True), (r'"C:\\Users\\alice\\x"', True),
                      ("/c/Users/alice/x", True), (r"C:\Users\alicex\y", False), ("~/x", False)]:
        f.write_text(text, encoding="utf-8")
        assert backup.has_home_path(f) is hit, text


def test_normalize_exports_are_stable():
    scoop = {"buckets": [{"Name": "main", "Source": "s", "Updated": "t"}],
             "apps": [{"Name": "b", "Source": "main", "Updated": "t1", "Version": "1"},
                      {"Name": "A", "Source": "<auto-generated>", "Version": "2", "Info": ""}]}
    out = json.loads(backup.normalize_export("scoop", scoop))
    assert [a["Name"] for a in out["apps"]] == ["A", "b"]
    assert "Updated" not in json.dumps(out) and out["apps"][0]["Version"] == "2" and "Version" not in out["apps"][1]
    winget = {"$schema": "s", "CreationDate": "today",
              "Sources": [{"Packages": [{"PackageIdentifier": "Z.z", "Version": "1"}, {"PackageIdentifier": "a.A"}],
                           "SourceDetails": {"Name": "winget"}}]}
    out = json.loads(backup.normalize_export("winget", winget))
    assert "CreationDate" not in out
    assert [p["PackageIdentifier"] for p in out["Sources"][0]["Packages"]] == ["a.A", "Z.z"]


