def test_ssh_config_parsing(tmp_path, monkeypatch):
    monkeypatch.setattr(restore, "home", lambda: tmp_path)
    ssh = tmp_path / ".ssh"
    ssh.mkdir()
    (ssh / "config").write_text(
        "# comment\n"
        "Host github.com\n"
        "    IdentityFile ~/.ssh/gh_key     # trailing comment\n"
        "Host srv\n"
        "    IdentityFile=\"~/.ssh/with space\"\n"
        "    identityfile %d/.ssh/third\n",
        encoding="utf-8")
    monkeypatch.setenv("HOME", str(tmp_path))
    keys, github = restore._ssh_config_keys()
    assert [k.name for k in keys] == ["id_ed25519", "gh_key", "with space", "third"]
    assert github.name == "gh_key"


